import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const QUEST_PRESENTATION_KEYS = Object.freeze([
  "ui.quest", "ui.close", "ui.previous", "ui.next", "ui.questTrack", "ui.questEmpty",
  "ui.questAccept", "ui.questComplete", "ui.questAbandon", "ui.questShare", "ui.questNoReward",
  "ui.questReturnHeading", "ui.questProgressHeading",
  "ui.questObjective", "ui.questReward", "ui.questRewardExp", "ui.questRewardGold",
  "ui.questRewardCredit", "ui.questRewardSelect", "ui.questTimeLimit", "ui.questStage.available",
  "ui.questStage.inProgress", "ui.questStage.readyToTurnIn", "ui.questStage.completed",
].sort());
export const QUEST_PRESENTATION_CODES = Object.freeze(["en", "es", "pt-BR", "zh-CN"]);

export function rustString(value) {
  return '"' + Array.from(value, character => {
    if (character === '"') return '\\"';
    if (character === "\\") return "\\\\";
    if (character === "\n") return "\\n";
    if (character === "\r") return "\\r";
    if (character === "\t") return "\\t";
    const code = character.codePointAt(0);
    return code < 32 || code === 127 ? `\\u{${code.toString(16)}}` : character;
  }).join("") + '"';
}

export function generateQuestPresentationText(canonical, web) {
  if (JSON.stringify(canonical) !== JSON.stringify(web)) throw new Error("Localization mirrors differ");
  const rows = QUEST_PRESENTATION_KEYS.map(key => {
    const values = QUEST_PRESENTATION_CODES.map(code => {
      const value = canonical.languages?.[code]?.texts?.[key];
      if (typeof value !== "string") throw new Error(`Missing canonical Quest text ${code}:${key}`);
      return rustString(value);
    });
    return `    (${rustString(key)}, [${values.join(", ")}]),`;
  });
  return "// Generated by build-quest-presentation-text.mjs. Do not edit.\n"
    + "// Codes: en, es, pt-BR, zh-CN. Only the approved Quest chrome subset.\n"
    + "pub const QUEST_PRESENTATION_TEXT: &[(&str, [&str; 4])] = &[\n" + rows.join("\n") + "\n];\n";
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
export function buildQuestPresentationText(check = false) {
  const read = relative => JSON.parse(fs.readFileSync(path.join(root, relative), "utf8"));
  const text = generateQuestPresentationText(read("packages/game-data/data/generated/localization_bundle.json"),
    read("apps/web/lib/generated/localization_bundle.json"));
  const target = path.join(root, "packages/game-data/data/generated/quest_presentation_text.rs");
  if (check) {
    if (fs.readFileSync(target, "utf8") !== text) throw new Error("Quest presentation table is stale");
  } else fs.writeFileSync(target, text);
  return text;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildQuestPresentationText(process.argv.includes("--check"));
  console.log(`Quest presentation subset: ${QUEST_PRESENTATION_KEYS.length} keys, ${Buffer.byteLength(text)} bytes`);
}
