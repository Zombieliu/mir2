let verifiedOriginalPngCount = 0;
let rejectedNegativeControls = 0;
for (const [name, required] of Object.entries(relevant)) {
  const sourceBytes = readFileSync(path.join(dataDir, name + ".Lib"));
  const sourceHash = sha256(sourceBytes);
  const source = parseLibrary(sourceBytes);
  const meta = JSON.parse(readFileSync(path.join(root, name, "meta.json"), "utf8"));
  if (meta.sourceLibrary) {
    assert.equal(meta.sourceLibrary.path, name + ".Lib");
    assert.equal(meta.sourceLibrary.sha256, sourceHash);
    assert.equal(meta.sourceLibrary.bytes, sourceBytes.length);
  }
  const indexed = new Map(meta.frames.map((frame) => [frame.index, frame]));
  assert.equal(indexed.size, meta.frames.length, name + " duplicate metadata IDs");
  for (const index of required) assert(indexed.has(index), name + "/" + index + " missing");
  const baseline = prior.find((entry) => entry.name === name);
  let preservedPriorPngCount = 0;
  if (baseline) {
    assert.equal(sourceHash, baseline.sourceLibrarySha256, name + " source library changed");
    const fingerprint = sha256(baseline.priorIndices.map((index) => {
      assert(indexed.has(index), name + "/" + index + " prior metadata removed");
      return index + ":" + sha256(readFileSync(path.join(root, name, index + ".png")));
    }).join("\n"));
    assert.equal(fingerprint, baseline.priorFingerprint, name + " prior PNG bytes changed");
    preservedPriorPngCount = baseline.priorIndices.length;
  }
  // Verify the entire touched Prguse/Title metadata denominator, not just the
  // added frames, plus the separate close-button and coin frames used here.
  const selected = baseline ? [...indexed.keys()].sort((a,b) => a-b) : required;
  for (const index of selected) {
    const entry = indexed.get(index);
    const frame = source.frames[index];
    assert(frame && frame.width > 0 && frame.height > 0, name + "/" + index + " source missing");
    for (const key of ["width","height","x","y"]) assert.equal(entry[key],frame[key],name + "/" + index + " " + key);
    const original = decodeFrameRgba(source, frame);
    const png = readFileSync(path.join(root, name, index + ".png"));
    if (entry.pngSha256) assert.equal(entry.pngSha256, sha256(png));
    if (entry.rgbaSha256) assert.equal(entry.rgbaSha256, sha256(original));
    const decoded = await sharp(png).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    const matches = (pixels,width,height) => width === frame.width && height === frame.height
      && decoded.info.channels === 4 && pixels.equals(original);
    assert(matches(decoded.data,decoded.info.width,decoded.info.height), name + "/" + index + " RGBA mismatch");
    verifiedOriginalPngCount++;
    if (required.includes(index)) {
      assert(!matches(decoded.data,decoded.info.width+1,decoded.info.height), "wrong width accepted");
      const wrong = Buffer.from(decoded.data); wrong[0] ^= 1;
      assert(!matches(wrong,decoded.info.width,decoded.info.height), "wrong pixel accepted");
      rejectedNegativeControls += 2;
      relevantFrames.push({library:name,index,width:frame.width,height:frame.height,x:frame.x,y:frame.y,
        pngSha256:sha256(png),rgbaSha256:sha256(original),newlyExported:requiredNew[name]?.includes(index) ?? false});
    }
  }
  libraries.push({name,sourceLibrarySha256:sourceHash,sourceLibraryBytes:sourceBytes.length,
    metadataFrameCount:meta.frames.length,verifiedOriginalPngCount:selected.length,preservedPriorPngCount,
    priorPngFingerprintSha256:baseline?.priorFingerprint ?? null});
}
assert.equal(relevantFrames.length,16);
assert.equal(relevantFrames.filter((f)=>f.newlyExported).length,5);
