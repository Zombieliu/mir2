import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url);
const output = new URL("lib/generated/r16-entry-bootstrap-chunks.ts", root);
const [mode, ...extra] = process.argv.slice(2);
assert((mode === undefined || mode === "--check") && extra.length === 0, "Only --check is supported");
const pins = ["scene", "floor"].map(kind => JSON.parse(readFileSync(new URL("lib/generated/r16-entry-" + kind + ".json", root))));
assert.equal(pins[0].assetReleaseId, pins[1].assetReleaseId);
assert.equal(pins[1].sceneSha256, pins[0].sha256);
const visuals = JSON.parse(readFileSync(new URL("lib/generated/r16-entry-visuals.json", root)));
assert.equal(visuals.assetReleaseId, pins[0].assetReleaseId);
assert.equal(visuals.sceneSha256, pins[0].sha256);
pins.push(visuals.monsterWalking);
const modes = ["json", "pretty-json-line", "json-line"];
for (const [i, pin] of pins.entries()) {
  assert.match(pin.path, /^\/bootstrap\/r16-(?:scenes|floor|visuals)\/[a-f0-9]{64}\.json$/);
  assert(pin.path.endsWith("/" + pin.sha256 + ".json"));
  const raw = readFileSync(new URL("public" + pin.path, root));
  assert.equal(raw.length, pin.bytes);
  assert.equal(createHash("sha256").update(raw).digest("hex"), pin.sha256);
  const value = JSON.parse(raw);
  const restored = modes[i] === "pretty-json-line" ? JSON.stringify(value, null, 2) + "\n"
    : JSON.stringify(value) + (modes[i] === "json-line" ? "\n" : "");
  assert.equal(restored, raw.toString("utf8"), "Compiled fallback must preserve the original bytes, not replace their pin");
}
const originalWalking = JSON.parse(readFileSync(new URL("public" + pins[2].path, root)));
assert.deepEqual(Object.keys(originalWalking), ["libraries", "images"]);
const parts = [], partValues = [];
for (const [libraryKey, library] of Object.entries(originalWalking.libraries)) {
  assert.match(libraryKey, /^Monster\/[0-9]{3}$/);
  const paths = new Set(library.frames.map(frame => frame.path));
  const images = Object.fromEntries(Object.entries(originalWalking.images).filter(([path]) => paths.has(path)));
  assert.equal(paths.size, 48);assert.equal(Object.keys(images).length, 48);
  const value = { libraries: { [libraryKey]: library }, images };
  const bytes = Buffer.from(JSON.stringify(value) + "\n"), sha256 = createHash("sha256").update(bytes).digest("hex");
  assert(bytes.length <= 256 * 1024);
  const path = `/bootstrap/r16-visual-parts/${pins[2].sha256}/${sha256}.json`;
  const file = new URL("public" + path, root);
  if (mode === "--check") assert.deepEqual(readFileSync(file), bytes, "Pinned walking part is stale");
  else { mkdirSync(new URL(".", file), { recursive: true });writeFileSync(file, bytes); }
  parts.push({ libraryKey, path, bytes: bytes.length, sha256 });partValues.push(value);
}
assert.equal(parts.length, 5);
const restoredWalking = { libraries: Object.fromEntries(partValues.flatMap(part => Object.entries(part.libraries))),
  images: Object.fromEntries(partValues.flatMap(part => Object.entries(part.images))) };
assert.equal(JSON.stringify(restoredWalking) + "\n", readFileSync(new URL("public" + pins[2].path, root), "utf8"));
const partManifest = JSON.stringify({ schemaVersion: 1, assetReleaseId: visuals.assetReleaseId,
  sourceSha256: pins[2].sha256, sourceBytes: pins[2].bytes, parts }, null, 2) + "\n";
const partOutput = new URL("lib/generated/r16-entry-walking-parts.json", root);
if (mode === "--check") assert.equal(readFileSync(partOutput, "utf8"), partManifest, "Walking parts manifest is stale");
else writeFileSync(partOutput, partManifest);
const text = `// Generated by scripts/generate-r16-bootstrap-chunks.mjs; do not edit.\n` +
  `import { createPinnedBootstrapChunk } from "../pinned-bootstrap-chunk";\n` +
  `import { joinPinnedEntryActorParts } from "../pinned-entry-actor-parts";\n` +
  `import scene from "./r16-entry-scene.json";\n` +
  `import floor from "./r16-entry-floor.json";\n` +
  `import visuals from "./r16-entry-visuals.json";\n` +
  `import walkingParts from "./r16-entry-walking-parts.json";\n` +
  `import type { SceneBlueprint } from "../scene-types";\n` +
  `import type { R16EntryActorAssets } from "../r16-entry-scene";\n\n` +
  `export const readR16EntrySceneChunk = createPinnedBootstrapChunk<SceneBlueprint>(\n` +
  `  scene, () => import(/* webpackChunkName: "r16-entry-scene-fallback" */ "../../public${pins[0].path}"), "json",\n);\n\n` +
  `export const readR16EntryFloorChunk = createPinnedBootstrapChunk<Readonly<Partial<Record<string, string>>>>(\n` +
  `  floor, () => import(/* webpackChunkName: "r16-entry-floor-fallback" */ "../../public${pins[1].path}"), "pretty-json-line",\n);\n\n` +
  `export const readR16EntryMonsterWalkingChunk = createPinnedBootstrapChunk<R16EntryActorAssets>(\n` +
  `  visuals.monsterWalking, signal => joinPinnedEntryActorParts([\n` +
  parts.map((part, index) => `    { ...walkingParts.parts[${index}], load: () => import(/* webpackChunkName: "r16-entry-monster-walking-${part.libraryKey.slice(-3)}-fallback" */ "../../public${part.path}") },\n`).join("") +
  `  ], signal), "json-line",\n);\n`;
if (mode === "--check") assert.equal(readFileSync(output, "utf8"), text, "Generated bootstrap chunk bindings are stale");
else writeFileSync(output, text);
console.log(JSON.stringify({ checked: mode === "--check", chunks: 7, walkingParts: parts.length,
  walkingPartBytes: parts.map(part => part.bytes), bytes: pins.map(p => p.bytes), exactPins: true }));
