import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const root = new URL("../", import.meta.url);
const output = new URL("lib/generated/r16-entry-bootstrap-chunks.ts", root);
const [mode, ...extra] = process.argv.slice(2);
assert((mode === undefined || mode === "--check") && extra.length === 0, "Only --check is supported");
const pins = ["scene", "floor"].map(kind => JSON.parse(readFileSync(new URL("lib/generated/r16-entry-" + kind + ".json", root))));
assert.equal(pins[0].assetReleaseId, pins[1].assetReleaseId);
assert.equal(pins[1].sceneSha256, pins[0].sha256);
const visuals = JSON.parse(readFileSync(new URL("lib/generated/r16-entry-visuals.json", root)));
assert.equal(visuals.assetReleaseId, pins[0].assetReleaseId);
assert.equal(visuals.sceneSha256, pins[0].sha256);
pins.push(visuals.monsterWalking);
const modes = ["json", "pretty-json-line", "json-line"];
for (const [i, pin] of pins.entries()) {
  assert.match(pin.path, /^\/bootstrap\/r16-(?:scenes|floor|visuals)\/[a-f0-9]{64}\.json$/);
  assert(pin.path.endsWith("/" + pin.sha256 + ".json"));
  const raw = readFileSync(new URL("public" + pin.path, root));
  assert.equal(raw.length, pin.bytes);
  assert.equal(createHash("sha256").update(raw).digest("hex"), pin.sha256);
  const value = JSON.parse(raw);
  const restored = modes[i] === "pretty-json-line" ? JSON.stringify(value, null, 2) + "\n"
    : JSON.stringify(value) + (modes[i] === "json-line" ? "\n" : "");
  assert.equal(restored, raw.toString("utf8"), "Compiled fallback must preserve the original bytes, not replace their pin");
}
const text = `// Generated by scripts/generate-r16-bootstrap-chunks.mjs; do not edit.\n` +
  `import { createPinnedBootstrapChunk } from "../pinned-bootstrap-chunk";\n` +
  `import scene from "./r16-entry-scene.json";\n` +
  `import floor from "./r16-entry-floor.json";\n` +
  `import visuals from "./r16-entry-visuals.json";\n` +
  `import type { SceneBlueprint } from "../scene-types";\n` +
  `import type { R16EntryActorAssets } from "../r16-entry-scene";\n\n` +
  `export const readR16EntrySceneChunk = createPinnedBootstrapChunk<SceneBlueprint>(\n` +
  `  scene, () => import(/* webpackChunkName: "r16-entry-scene-fallback" */ "../../public${pins[0].path}"), "json",\n);\n\n` +
  `export const readR16EntryFloorChunk = createPinnedBootstrapChunk<Readonly<Partial<Record<string, string>>>>(\n` +
  `  floor, () => import(/* webpackChunkName: "r16-entry-floor-fallback" */ "../../public${pins[1].path}"), "pretty-json-line",\n);\n\n` +
  `export const readR16EntryMonsterWalkingChunk = createPinnedBootstrapChunk<R16EntryActorAssets>(\n` +
  `  visuals.monsterWalking, () => import(/* webpackChunkName: "r16-entry-monster-walking-fallback" */ "../../public${pins[2].path}"), "json-line",\n);\n`;
if (mode === "--check") assert.equal(readFileSync(output, "utf8"), text, "Generated bootstrap chunk bindings are stale");
else writeFileSync(output, text);
console.log(JSON.stringify({ checked: mode === "--check", chunks: 3, bytes: pins.map(p => p.bytes), exactPins: true }));
