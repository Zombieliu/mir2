const envelope = (packet = 'NewItemInfo', index = 1) => ({ type: 'packet', packet, payload: { index, name: '药品 Potion' } });
function rawBatch(body, count = 1, length = body.length) {
  const header = Buffer.alloc(16); header.write('M2CATGZ1'); header.writeUInt32LE(length, 8); header.writeUInt32LE(count, 12);
  return Buffer.concat([header, gzipSync(body)]);
}
function batch(texts) {
  return rawBatch(Buffer.concat(texts.map(text => {
    const bytes = Buffer.from(text), prefix = Buffer.alloc(4); prefix.writeUInt32LE(bytes.length);
    return Buffer.concat([prefix, bytes]);
  })), texts.length);
}
const encoded = messages => batch(messages.map(message => JSON.stringify(message)));

test('catalog framing preserves Unicode, fields and original envelope order', () => {
  const messages = ['NewItemInfo', 'NewRecipeInfo', 'GameShopInfo', 'NewQuestInfo'].map(envelope);
  assert.deepEqual(decodeCatalogBatch(encoded(messages)), messages);
  assert.deepEqual(decodeCatalogBatch(new Uint8Array(encoded(messages))), messages);
  assert.deepEqual(decodePlaytestFrame(encoded(messages), true), messages);
});

