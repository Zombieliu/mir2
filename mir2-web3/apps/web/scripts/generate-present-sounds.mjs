// Generates a manifest of the sound files that resolve at runtime, i.e. the published Crystal
// sound set the client is allowed to request.
//
// History: this manifest used to list ONLY the handful of .wav bytes committed under
// public/original-ui/Sound, because the full set was not yet uploaded anywhere — resolving
// against that tiny set turned every other id into a clean "missing" result so the client never
// fired a doomed request. That guard is now obsolete: the full Crystal sound library (the 320
// distinct .wav files the 450 SoundList ids reference) belongs to the external/private asset
// release and is served at /original-ui/Sound/... when that release is configured. It is not
// committed to Git. Gating playback on local-disk presence would therefore silence release
// sounds even when their remote bytes are available.
//
// The present set is now the union of:
//   1. any .wav actually committed under public/original-ui/Sound (so a local checkout stays
//      authoritative for files it does carry), and
//   2. every distinct file referenced by the committed sound index
//      (public/original-ui/sound-index.generated.json) with sourceExists + a public path — that
//      index is generated against the full client export and is the source of truth for what the
//      release publishes.
// With an external release both resolve remotely; in a bytes-limited local checkout the request
// can 404 and the audio layer degrades gracefully. A strict local audio release check remains
// available through MIR2_REQUIRE_LOCAL_SOUND_CLOSURE=1 in preflight-asset-release.mjs.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const soundDir = fileURLToPath(new URL("../public/original-ui/Sound", import.meta.url));
const soundIndexPath = fileURLToPath(new URL("../public/original-ui/sound-index.generated.json", import.meta.url));
const outputPath = fileURLToPath(new URL("../lib/generated/crystal-present-sounds.generated.json", import.meta.url));

function basename(value) {
  return String(value).split("/").pop() ?? "";
}

// 1. Files physically committed under public/original-ui/Sound.
let committed = [];
try {
  committed = readdirSync(soundDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /\.wav$/i.test(entry.name))
    .map((entry) => entry.name);
} catch {
  committed = [];
}

// 2. Files the published sound index marks as existing (the full release set).
let indexed = [];
try {
  const index = JSON.parse(readFileSync(soundIndexPath, "utf8"));
  const sounds = index?.sounds ?? {};
  indexed = Object.values(sounds)
    .filter((entry) => entry && entry.sourceExists && entry.path)
    .map((entry) => basename(entry.path))
    .filter((name) => /\.wav$/i.test(name));
} catch {
  indexed = [];
}

// Union, de-duplicated case-insensitively (keep first-seen casing), deterministically sorted.
const seen = new Set();
const files = [];
for (const name of [...committed, ...indexed]) {
  const key = name.toLowerCase();
  if (seen.has(key)) continue;
  seen.add(key);
  files.push(name);
}
files.sort((left, right) => left.localeCompare(right));

// Deterministic on purpose (no generatedAt timestamp): this manifest is a committed build input
// regenerated by the offline asset pipeline, so it must only change when the set of present sound
// files actually changes — otherwise every pipeline run would dirty the tree.
const payload = {
  schemaVersion: 1,
  kind: "mir2-present-sound-manifest",
  soundDir: "public/original-ui/Sound",
  presentSoundCount: files.length,
  files,
};

mkdirSync(path.dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(payload, null, 2)}\n`);

console.log(
  JSON.stringify({ ok: true, outputPath, presentSoundCount: files.length, committedCount: committed.length }, null, 2),
);
