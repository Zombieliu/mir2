// Generates a manifest of the sound files that are ACTUALLY present under
// public/original-ui/Sound. The committed Crystal sound index
// (public/original-ui/sound-index.generated.json) was produced against a full client export
// and marks all ~450 sounds as existing, but only a handful of .wav bytes are committed to the
// repo (the full set is large and gated on the raw Crystal client). Without this manifest the
// client would resolve paths for sounds whose bytes 404 at runtime. Resolving against the real
// present set turns those into clean "missing" results (no doomed network request) and lets the
// audio diagnostics report accurate coverage.
//
// This script operates purely on committed files, so it runs in any environment (no
// CRYSTAL_CLIENT_ROOT required).
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const soundDir = fileURLToPath(new URL("../public/original-ui/Sound", import.meta.url));
const outputPath = fileURLToPath(new URL("../lib/generated/crystal-present-sounds.generated.json", import.meta.url));

const files = readdirSync(soundDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && /\.wav$/i.test(entry.name))
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right));

// Deterministic on purpose (no generatedAt timestamp): this manifest is a committed build
// input regenerated by the offline asset pipeline, so it must only change when the set of
// present sound files actually changes — otherwise every pipeline run would dirty the tree.
const payload = {
  schemaVersion: 1,
  kind: "mir2-present-sound-manifest",
  soundDir: "public/original-ui/Sound",
  presentSoundCount: files.length,
  files,
};

mkdirSync(path.dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(payload, null, 2)}\n`);

console.log(
  JSON.stringify({ ok: true, outputPath, presentSoundCount: files.length, files }, null, 2),
);
