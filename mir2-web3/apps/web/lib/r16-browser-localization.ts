for (const language of R16_BROWSER_LANGUAGES) Object.freeze(dictionaries[language]);
export const R16_BROWSER_DICTIONARIES = Object.freeze(dictionaries);

/** Unknown keys/languages deliberately yield to the caller's existing fallback. */
export function browserText(language: string, key: string): string | undefined {
  if (!Object.hasOwn(R16_BROWSER_DICTIONARIES, language)) return undefined;
  const dictionary = R16_BROWSER_DICTIONARIES[language as R16NativeLanguage];
  if (!Object.hasOwn(dictionary, key)) return undefined;
  const value = dictionary[key as R16BrowserTextKey];
  return value.trim() ? value : undefined;
}
