export const R16_COMPANION_MESSAGE_KEYS = Object.keys(en) as R16CompanionMessage[];

export function r16CompanionPresentation(language: Mir2Language) {
  const info = nativeLanguageInfo(language) ?? nativeLanguageInfo("en")!;
  const dictionary = info.code === "zh-CN" ? zhCN : info.code === "ar" ? ar : additional[info.code];
  const copy: R16CompanionCopy = (key, ...args) => {
    const template = dictionary?.[key] ?? en[key];
    return template.replace(/\{(\d+)\}/g, (token, index) => args[Number(index)] === undefined ? token : String(args[Number(index)]));
  };
  return { language: info.code, locale: info.locale, dir: info.dir, fontFamily: info.fontFamily, copy };
}

// The transport publishes these authored notices. Match only this finite set;
// owner text and model/server narrative enter the UI as opaque strings.
const noticeKeys = [
  "noticeWaiting", "noticeNotSent", "noticeUnknown", "noticeDenied", "noticeOffline", "noticeConflict",
  "noticeInvalid", "noticeError", "noticeList", "noticeEmpty", "noticeSupply", "noticeSupplyCancel",
  "noticeInterest", "noticeTrial", "noticeMalformed", "noticeExportExpired", "noticeExportChecking",
  "noticeExportReady", "noticeExportFailed",
] as const;
const noticeBySource = new Map<string, R16CompanionMessage>(noticeKeys.map(key => [zhCN[key], key]));

export function r16CompanionNotice(source: string, copy: R16CompanionCopy): string {
  const known = noticeBySource.get(source);
  if (known) return copy(known);
  const version = /^(教学已保存，培养版本|已读取服务器记录，培养版本) v(\d+)。$/.exec(source);
  return version ? copy(version[1] === "教学已保存，培养版本" ? "noticeTeach" : "noticeView", version[2]) : source;
}
