export async function getAdminI18n(): Promise<AdminI18n> {
  const cookieStore = await cookies();
  const locale = normalizeAdminLocale(cookieStore.get(COOKIE_NAME)?.value);
  return {
    locale,
    t: (key, values) => interpolate(dictionaries[locale][key] ?? dictionaries.en[key] ?? key, values)
  };
}

export function normalizeAdminLocale(value: string | undefined | null): AdminLocale {
  return value === "zh-CN" || value === "zh" || value === "zh-cn" ? "zh-CN" : "en";
}

