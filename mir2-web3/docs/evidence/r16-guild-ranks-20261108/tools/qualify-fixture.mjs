import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const base=import.meta.dirname+'/browser-realm';
const sha=b=>createHash('sha256').update(b).digest('hex');
const oldSeed=await readFile(base+'/private-qa/accounts.seeded-snapshot.json');
const live=await readFile(base+'/private-data/accounts.json');
assert.deepEqual(JSON.parse(live),JSON.parse(oldSeed),'Invalid fixture must not have accepted account-store mutations');
const store=JSON.parse(live),old='r16-guild-rank-fixture';
const guild=store.sharedGuilds[old];assert(guild);assert.equal(Object.keys(store.sharedGuilds).length,1);
const id=sha('r16-guild-rank-fixture-20261108').slice(0,32);
assert.match(id,/^[0-9a-f]{32}$/);delete store.sharedGuilds[old];guild.id=id;store.sharedGuilds[id]=guild;
assert.equal(new Set(guild.members.map(m=>m.identity.characterIndex)).size,3);
assert.deepEqual(store.accounts,JSON.parse(oldSeed).accounts);
await writeFile(base+'/private-qa/accounts.invalid-fixture-after.json',live,{flag:'wx',mode:0o600});
const qualified=Buffer.from(JSON.stringify(store));
await writeFile(base+'/private-qa/accounts.qualified-snapshot.json',qualified,{flag:'wx',mode:0o600});
await writeFile(base+'/private-data/accounts.json',qualified,{mode:0o600});
const launcher=(await readFile(base+'/launch-realm.mjs','utf8')).replaceAll('gateway.private.log','gateway-qualified.private.log').replaceAll('gateway-ready.json','gateway-qualified-ready.json');
await writeFile(base+'/launch-realm-qualified.mjs',launcher,{flag:'wx'});
await writeFile(base+'/fixture-qualification.json',JSON.stringify({schema:'mir2.r16.guild-fixture-qualification.v1',recordedAt:new Date().toISOString(),invalidSeedSha256:sha(oldSeed),invalidAfterSha256:sha(live),qualifiedSnapshotSha256:sha(qualified),personalAccountsUnchanged:true,members:3,stableGuildIdFormatValid:true,uniquePublicCharacterIndices:true,previousServerRejectedInvalidId:true,productSourceChanged:false},null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({fixtureQualified:true,personalAccountsUnchanged:true,members:3}));
