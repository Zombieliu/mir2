import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=dirname(fileURLToPath(import.meta.url));
const [priorFile,nextFile,label]=process.argv.slice(2);
assert.match(label??'',/^[a-z0-9-]+$/);
const adb='/Users/henryliu/Library/Android/sdk/platform-tools/adb';
const run=args=>execFileSync(adb,['-s','emulator-5554',...args],{timeout:60000,maxBuffer:32*1024*1024});
const save=(name,data)=>writeFileSync(join(root,label+'-'+name),data,{flag:'wx'});
assert.match(run(['emu','avd','name']).toString(),/^Mir2_API_31_ARM64/);
assert.equal(run(['shell','getprop','ro.build.version.sdk']).toString().trim(),'31');
const old=JSON.parse(readFileSync(join(root,priorFile))),next=JSON.parse(readFileSync(join(root,nextFile)));
const artifact=p=>p.artifacts.find(a=>a.variant==='preview');
const oldPath=run(['shell','pm','path','com.mir2.web3.uipreview']).toString().trim().replace(/^package:/,'');
const oldSha=run(['shell','sha256sum',oldPath]);
assert.equal(oldSha.toString().split(/\s+/)[0],artifact(old).sha256);save('previous-installed-sha.txt',oldSha);
const a=artifact(next);assert.equal(createHash('sha256').update(readFileSync(a.path)).digest('hex'),a.sha256);
const result=run(['install','-r',a.path]);save('install.txt',result);assert.match(result.toString(),/Success/);
const p=run(['shell','pm','path','com.mir2.web3.uipreview']);save('installed-path.txt',p);
const s=run(['shell','sha256sum',p.toString().trim().replace(/^package:/,'')]);save('installed-sha.txt',s);
assert.equal(s.toString().split(/\s+/)[0],a.sha256);
const pkg=run(['shell','dumpsys','package','com.mir2.web3.uipreview']);save('installed-package.txt',pkg);
assert.match(pkg.toString(),new RegExp('versionCode='+next.versionCode+'\\b'));
console.log(JSON.stringify({source:next.source,sha256:a.sha256,versionCode:next.versionCode,dataPreservingUpdate:true}));
