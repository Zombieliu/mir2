import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawn} from 'node:child_process';
const project='C:/Users/Administrator/.codex/worktrees/cell-preproduction-p0-p1/mir2-player-journey/mir2-web3';
const directory='C:/mir2-build/p01-completion-20261024/root-navigation-workspace-validation-v2';
await fs.mkdir(directory,{recursive:true});
const files=['apps/web/scripts/quest-agent/protocol-navigation.mjs','apps/web/scripts/quest-agent/test-protocol-navigation.mjs','apps/web/scripts/playtest-capacity-soak.test.mjs','apps/web/scripts/playtest-capacity-observability.test.mjs','apps/web/scripts/playtest-capacity-monitor.test.mjs','apps/web/scripts/playtest-capacity-telemetry.test.mjs'];
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const pin=async relative=>{const b=await fs.readFile(path.join(project,relative));return{file:relative,bytes:b.length,sha256:sha(b)}};
const before=await Promise.all(files.map(pin));
const args=['--test',...files.slice(2)];
