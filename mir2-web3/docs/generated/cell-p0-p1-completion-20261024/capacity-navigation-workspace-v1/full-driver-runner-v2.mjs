const summary=output.split(/\r?\n/).filter(x=>/^# (tests|pass|fail|cancelled|skipped|todo|duration_ms) /.test(x));
const record={schemaVersion:1,startedAt,finishedAt:new Date().toISOString(),command:[process.execPath,...args],cwd:project,...result,error,before,after,sourceUnchanged:JSON.stringify(before)===JSON.stringify(after),summary,capacityAccepted:false,p0Accepted:false};
await fs.writeFile(path.join(directory,'full-driver-receipt-v1.json'),JSON.stringify(record,null,2)+'\n',{flag:'wx'});
