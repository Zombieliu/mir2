function buildSelectPortraitSequence(
  startIndex: number,
  offsets: Array<[number, number]>,
): SelectPortraitFrame[] {
  return offsets.map(([x, y], frameIndex) => ({
    path: `/original-ui/ChrSel/${startIndex + frameIndex}.png`,
    x,
    y,
  }));
}

